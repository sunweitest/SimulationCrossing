def upgrade():
    conn = op.get_bind()

    # ── 插入小说 ──
    novel_row = conn.execute(
        sa.text("SELECT id FROM novel_configs WHERE name = :name"),
        {"name": NOVEL_NAME},
    ).fetchone()
    if novel_row is None:
        novel_row = conn.execute(
            sa.text(
                "INSERT INTO novel_configs (name, description, sort_order) "
                "VALUES (:name, :desc, :sort) RETURNING id"
            ),
            {"name": NOVEL_NAME, "desc": NOVEL_DESCRIPTION, "sort": 7},
        ).fetchone()
    novel_id = novel_row[0]

    # ── 插入时间节点 ──
    for tl_name, sort_order, desc in TIMELINE_SEEDS:
        tl_existing = conn.execute(
            sa.text(
                "SELECT id FROM timeline_configs WHERE novel_id = :nid AND name = :name"
            ),
            {"nid": novel_id, "name": tl_name},
        ).fetchone()
        if tl_existing is None:
            conn.execute(
                sa.text(
                    "INSERT INTO timeline_configs (novel_id, name, description, sort_order) "
                    "VALUES (:nid, :name, :desc, :sort)"
                ),
                {"nid": novel_id, "name": tl_name, "desc": desc, "sort": sort_order},
            )

    # ── 插入角色 ──
    for novel, name, gender, age, rank, bg, pts, timelines in NEW_CHARACTERS:
        existing = conn.execute(
            sa.text(
                "SELECT id FROM preset_characters WHERE novel = :novel AND name = :name"
            ),
            {"novel": novel, "name": name},
        ).fetchone()

        if existing:
            char_id = existing[0]
        else:
            row = conn.execute(
                sa.text(
                    "INSERT INTO preset_characters (novel, name, gender, age, rank, background, starting_points) "
                    "VALUES (:novel, :name, :gender, :age, :rank, :bg, :pts) RETURNING id"
                ),
                {"novel": novel, "name": name, "gender": gender, "age": age, "rank": rank, "bg": bg, "pts": pts},
            ).fetchone()
            char_id = row[0]

        for tl, tl_bg, tl_scene in timelines:
            tl_existing = conn.execute(
                sa.text(
                    "SELECT id FROM character_timelines WHERE character_id = :cid AND timeline = :tl"
                ),
                {"cid": char_id, "tl": tl},
            ).fetchone()
            if not tl_existing:
                conn.execute(
                    sa.text(
                        "INSERT INTO character_timelines (character_id, timeline, background, initial_scene) "
                        "VALUES (:cid, :tl, :bg, :scene)"
                    ),
                    {"cid": char_id, "tl": tl, "bg": tl_bg, "scene": tl_scene},
                )


